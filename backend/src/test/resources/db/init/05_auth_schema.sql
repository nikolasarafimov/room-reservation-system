DO $$
BEGIN
    IF current_database() <> 'room_reservation' THEN
        RAISE EXCEPTION
            'Safety check failed: expected database room_reservation, found %',
            current_database();
END IF;

    IF to_regclass('project.users') IS NULL THEN
        RAISE EXCEPTION 'Required table project.users does not exist';
END IF;
END;
$$;

ALTER TABLE project.users
    ADD COLUMN IF NOT EXISTS password_hash VARCHAR(255);

ALTER TABLE project.users
    ADD COLUMN IF NOT EXISTS enabled BOOLEAN NOT NULL DEFAULT TRUE;

COMMENT ON COLUMN project.users.password_hash IS
    'Password hash generated by the application password encoder. Never store plaintext passwords.';

COMMENT ON COLUMN project.users.enabled IS
    'False disables authentication for this account.';